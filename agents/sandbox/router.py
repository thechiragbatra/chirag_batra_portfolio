"""The edge router: one nginx container that maps http://<app>.localhost:<port> to the
live deploy of each app.

Static deploys are served from disk (SPA fallback to index.html); server deploys are
proxied to their container on the internal apps network. Switching or rolling back
a deploy rewrites the config and reloads nginx, so the change is atomic. nginx runs
unprivileged with the same hardening as the app containers and is published on
127.0.0.1 only.
"""

from __future__ import annotations

import asyncio
import os

from agents.sandbox.docker import (
    APPS_NETWORK,
    LABEL,
    ROUTER_IMAGE,
    SandboxError,
    container_running,
    docker,
    ensure_network,
    remove_container,
)
from agents.sandbox.recipes import APP_PORT
from agents.sandbox.store import AppRecord, Store, container_name

ROUTER_NAME = "deploysmith-router"
ROUTER_UID = "101:101"  # the nginx user in the official image
DOCKER_DNS = "127.0.0.11"


def router_port() -> int:
    return int(os.getenv("DEPLOYSMITH_ROUTER_PORT", "8080"))


def app_url(app: str, port: int | None = None) -> str:
    return f"http://{app}.localhost:{port or router_port()}"


NGINX_MAIN = """\
# Generated by DeploySmith. Runs as an unprivileged user on a read-only filesystem.
worker_processes 1;
pid /tmp/nginx.pid;
error_log /dev/stderr warn;
events { worker_connections 512; }
http {
    include /etc/nginx/mime.types;
    default_type application/octet-stream;
    access_log off;
    server_tokens off;
    sendfile on;
    client_max_body_size 10m;
    client_body_temp_path /tmp/client_body;
    proxy_temp_path /tmp/proxy;
    fastcgi_temp_path /tmp/fastcgi;
    uwsgi_temp_path /tmp/uwsgi;
    scgi_temp_path /tmp/scgi;
    map $http_upgrade $connection_upgrade { default upgrade; '' close; }
    include /etc/deploysmith/sites.conf;
}
"""


def _static_server(record: AppRecord, deploy_id: str) -> str:
    root = f"/srv/apps/{record.name}/deploys/{deploy_id}/site"
    return f"""
server {{
    listen 8080;
    server_name {record.name}.localhost;
    add_header X-DeploySmith-Deploy {deploy_id} always;
    root {root};
    disable_symlinks on;
    location / {{ try_files $uri $uri/ $uri.html /index.html =404; }}
}}
"""


def _proxy_server(record: AppRecord, deploy_id: str) -> str:
    upstream = f"http://{container_name(record.name, deploy_id)}:{APP_PORT}"
    return f"""
server {{
    listen 8080;
    server_name {record.name}.localhost;
    add_header X-DeploySmith-Deploy {deploy_id} always;
    location / {{
        resolver {DOCKER_DNS} valid=5s ipv6=off;
        set $upstream {upstream};
        proxy_pass $upstream;
        proxy_http_version 1.1;
        proxy_set_header Host $http_host;
        proxy_set_header X-Forwarded-Host $http_host;
        proxy_set_header X-Forwarded-Port $server_port;
        proxy_set_header X-Forwarded-For $remote_addr;
        proxy_set_header X-Forwarded-Proto http;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection $connection_upgrade;
        proxy_read_timeout 300s;
    }}
}}
"""


def sites_config(records: list[AppRecord]) -> str:
    """nginx server blocks for every app with a live deploy. Pure, for tests."""
    parts = [
        "# Generated by DeploySmith; rewritten on every deploy, rollback and stop.\n",
        "server {\n    listen 8080 default_server;\n    default_type text/plain;\n"
        '    return 404 "No app is deployed at this address.\\n";\n}\n',
    ]
    for record in sorted(records, key=lambda r: r.name):
        if record.current is None:
            continue
        # The live deploy's own mode decides, not the record's: a failed deploy of a
        # different kind must not change how the live one is served.
        live = record.deployment(record.current)
        mode = live.mode if live else record.mode
        render = _static_server if mode == "static" else _proxy_server
        parts.append(render(record, record.current))
    return "".join(parts)


def write_config(store: Store) -> None:
    store.router_dir.mkdir(parents=True, exist_ok=True)
    (store.router_dir / "nginx.conf").write_text(NGINX_MAIN)
    tmp = store.router_dir / "sites.conf.tmp"
    tmp.write_text(sites_config(store.list()))
    os.replace(tmp, store.router_dir / "sites.conf")


def router_run_args(store: Store, port: int) -> list[str]:
    apps = store.root / "apps"
    return [
        "docker", "run", "--detach",
        "--name", ROUTER_NAME,
        "--label", LABEL,
        "--restart", "unless-stopped",
        "--user", ROUTER_UID,
        "--cap-drop", "ALL",
        "--security-opt", "no-new-privileges",
        "--read-only",
        "--tmpfs", "/tmp:rw,nosuid,nodev,size=64m",
        "--memory", "128m",
        "--pids-limit", "64",
        "--publish", f"127.0.0.1:{port}:8080",
        "--volume", f"{store.router_dir / 'nginx.conf'}:/etc/nginx/nginx.conf:ro",
        "--volume", f"{store.router_dir}:/etc/deploysmith:ro",
        "--volume", f"{apps}:/srv/apps:ro",
        ROUTER_IMAGE,
    ]  # fmt: skip


_reload_lock: asyncio.Lock | None = None


def _lock() -> asyncio.Lock:
    global _reload_lock
    if _reload_lock is None:
        _reload_lock = asyncio.Lock()
    return _reload_lock


async def _router_matches(store: Store, port: int) -> bool:
    """True if the running router publishes `port` and serves this store's directories.

    Otherwise a changed DEPLOYSMITH_ROUTER_PORT or DEPLOYSMITH_ENGINE_DIR would leave a
    stale router answering on the wrong port or serving another store's apps.
    """
    code, output = await docker(
        "inspect",
        "--format",
        '{{(index (index .HostConfig.PortBindings "8080/tcp") 0).HostPort}} '
        "{{range .Mounts}}{{.Source}};{{end}}",
        ROUTER_NAME,
    )
    if code != 0:
        return False
    published, _, mounts = output.strip().partition(" ")
    return published == str(port) and f"{store.root / 'apps'};" in mounts


async def _nginx_reload(attempts: int = 3) -> None:
    """Reload nginx. Retried briefly: a router another process has just started may
    not have written its pid file yet."""
    output = ""
    for attempt in range(attempts):
        code, output = await docker("exec", ROUTER_NAME, "nginx", "-s", "reload")
        if code == 0:
            return
        if attempt + 1 < attempts:
            await asyncio.sleep(1.0)
    raise SandboxError(f"router reload failed: {output}")


async def reload_router(store: Store) -> None:
    """Write the config, start (or recreate) the router if needed, and reload it.

    Serialized within the process, since concurrent deploys would otherwise race to
    create the router container. Two backend processes sharing one store are handled
    by treating "name already in use" as "someone else just created it".
    """
    async with _lock():
        write_config(store)
        (store.root / "apps").mkdir(parents=True, exist_ok=True)
        await ensure_network()

        port = router_port()
        if await container_running(ROUTER_NAME) and await _router_matches(store, port):
            await _nginx_reload()
            return

        await remove_container(ROUTER_NAME)
        code, output = await docker(*router_run_args(store, port)[1:])
        if code != 0 and "already in use" in output:
            await _nginx_reload()
            return
        if code != 0:
            raise SandboxError(f"could not start the router: {output}")
        code, output = await docker("network", "connect", APPS_NETWORK, ROUTER_NAME)
        if code != 0 and "already exists" not in output:
            raise SandboxError(f"could not attach the router to {APPS_NETWORK}: {output}")
